-- 开书向导门禁开关（W6 统一确认门禁）
-- 依据：用户 2026-09-25 诉求「最后确认一切前置信息后，再开始写作」
-- ═══════════════════════════════════════════════════════════════════
--
-- ## 为什么需要一个**独立**的开关，而不是复用 settings_gate_enabled
--
-- 两道门禁管的是**不同的事**：
--
--   settings_gate_enabled  → 「作者写的世界设定确认了吗」
--                            拦的是：设定有改动却没确认
--   blueprint_gate_enabled → 「开书向导的前置流程走完了吗」
--                            拦的是：向导用了但没走完统一确认
--
-- 合成一个开关的后果：作者想关掉其中一道时，另一道也跟着关了。
-- 而用户明确选了「向导可选，不强制」—— 那么"不想用向导"就必须能
-- **单独**关掉向导门禁，同时保留设定门禁。
--
-- ## 默认值 1（启用）的理由
--
-- 与 settings_gate_enabled 一致。注意门禁的实际判定里有一条
-- `NOT_USED`：四步全部未开始 → 放行（向导可选）。
-- 所以"默认启用"不等于"强迫所有人走向导"——
-- 没用过向导的书照样直接开写，只是**用过就得走完**。
--
-- ⚠ 这正是"向导可选"与"前置未确认不许开写"两句话能同时成立的地方：
--   可选 = 你可以不用；不强制 = 用了之后不会白用（生成的内容真的进 prompt）。
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE books ADD COLUMN blueprint_gate_enabled INTEGER NOT NULL DEFAULT 1
  CHECK (blueprint_gate_enabled IN (0, 1));
