-- M1：状态提议的版本锚点（第二阶段施工单 §21 / §22）
-- 依据：施工单 §19–§22；ADR-0008 §3
-- ═══════════════════════════════════════════════════════════════════
--
-- ## 为什么需要锚点
--
-- 施工单 §22 要求形成完整版本一致性机制：
--
--     Manuscript ── hash A ──┬── Review(hash A)
--                            ├── Continuity(hash A)
--                            └── State(hash A)
--
-- 正文一旦被改动（hash A → hash B），这三份结论**都**必须判 STALE，
-- 不能拿旧结果继续 Commit。
--
-- ## ⚠ 为什么不是复用 workflow_artifacts.content_hash
--
-- 施工计划与 ADR-0008 §3 曾设想复用该列。核对代码后确认**不成立**：
--
--     workflow-engine.ts:223
--       const actualHash = hashOfFile(a.path) ?? a.contentHash;
--
-- 它算的是**报告文件自身**的哈希（review.json 的内容哈希），
-- 不是被检查正文的哈希。拿报告哈希去比正文哈希，两者永不相等 ——
-- 表现是"刚跑完检查就判 STALE"，看起来像时序 bug，实际是拿错了对象。
--
-- 所以锚点是**语义明确的新字段**：source_hash = 这份结论所依据的
-- 正文内容的 sha256（与 @nwa/harness 的 sha256() 同算法同编码）。
--
-- ## 为什么状态提议的锚点要落在库里（而不是工作区文件）
--
-- 状态提议（state_proposals）已经是**落库**的：硬约束「没有 VERIFIED
-- 的 State Proposal 不得进入 Canon」需要可查证的门禁依据，进程重启后
-- 仍要能回答"这一章的结算做过没有"。锚点如果放在工作区文件里，
-- 就会出现"提议在库里、锚点在文件里"的分裂 —— 文件被清理后
-- 提议的版本归属就永久丢失了。
--
-- ## 为什么允许 NULL
--
-- 0016 之前落下的提议没有这个信息，且**不可事后推断**
-- （正文可能已被改动多次）。填一个猜测值比留空更糟：
-- 留空表示"无法确认对应哪一版"，判定时按 NO_ANCHOR 处理 ——
-- 宁严不宽，但如实说明原因（见 @nwa/core 的 staleness.ts）。
--
-- ⚠ 不加索引：查询路径是 `WHERE chapter_id = ? ORDER BY created_at`，
--   已有 idx_state_proposals_chapter 覆盖。source_hash 只作取值比对，
--   不需要独立索引（加索引只有写放大，同 0013/0014 的判断）。
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE state_proposals ADD COLUMN source_hash TEXT;
