--   - `ord`：作者写设定的顺序有意义（势力列表、地理层级），
--     按 created_at 排序在同一秒内不稳定

ALTER TABLE world_entities ADD COLUMN status TEXT NOT NULL DEFAULT 'DRAFT'
  CHECK (status IN ('DRAFT', 'CONFIRMED'));

ALTER TABLE world_entities ADD COLUMN ord INTEGER NOT NULL DEFAULT 0;
