-- P2-3：设定确认门禁（作者先写设定 → 确认锁定 → 才允许开写）
-- 依据：用户决策 2026-09-25 ——「作者先写设定 → Agent 按设定写」
--                                 「三个一起做，按完整度排优先级」
-- ═══════════════════════════════════════════════════════════════════
--
-- ## 为什么需要"确认"这一步
--
-- 前置设定（世界观 / 角色）如果只是"写在那里"，Agent 无法区分
-- 「作者已定稿的设定」与「作者随手记的草稿」。两者混在一起会有两个后果：
--
--   1. 草稿被当成权威设定写进正文，作者得回头改稿；
--   2. 作者改了设定但没告诉 Agent，正文与设定悄悄分叉 ——
--      这正是连续性检查最难发现的一类（没有矛盾，只是"不是那个设定"）。
--
-- 「确认」这个动作把"草稿"变成"Canon"，并把**当时的内容指纹**记下来。
-- 之后只要设定再被改动，指纹就对不上 → 自动退回未确认。
-- 这样"确认"才是一个有意义的承诺，而不是一次性的点击。
--
-- ## 为什么存"内容指纹"而不是布尔量
--
-- 只存 `settings_confirmed = 1` 的话，"确认后又改了设定"这个状态
-- 无法表达 —— 除非在每个写设定的入口都记得把标记清掉。
-- 那是"靠流程纪律维持的一致性"，一旦新增一个入口就漏。
-- 存指纹则是**读时判定**：任何入口改了设定，指纹自然对不上，
-- 不需要任何入口配合。这类"不依赖调用方守规矩"的设计在本项目里是硬要求
-- （同 `chapters.approveSummary()` 的预算 guard）。
--
-- ## 为什么门禁可关闭（gate_enabled）
--
-- 已存在的老项目（以及批量验证脚本）在引入本门禁前就已开写。
-- 若门禁无条件生效，升级后这些项目会**突然写不动**，
-- 而作者没有任何入口把它关掉 —— 那是把工具变成障碍。
-- 所以：默认开启，但可按书关闭；关闭是显式动作，且状态可查。
--
-- ⚠ 不加索引：books 是"一本书一行"，全表扫描本就是常数级
--   （同 0013 的判断，加索引只有写放大）。

ALTER TABLE books ADD COLUMN settings_gate_enabled INTEGER NOT NULL DEFAULT 1
  CHECK (settings_gate_enabled IN (0, 1));

-- NULL = 从未确认过 / 确认后设定又被改动（指纹对不上）
ALTER TABLE books ADD COLUMN settings_confirmed_hash TEXT;

ALTER TABLE books ADD COLUMN settings_confirmed_at TEXT;

