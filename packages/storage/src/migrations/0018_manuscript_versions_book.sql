-- 按书隔离（审查报告 P0-1）：manuscript_versions 补 book_id
-- 依据：审查报告 P0-1；用户 2026-09-25 决策「books/<bookId>/chapters/001.md」
-- ═══════════════════════════════════════════════════════════════════
--
-- ## 为什么版本表也需要 book_id
--
-- 版本内容文件落在 `workspace/chapter-NNN/versions/vNNN.md`，
-- 而那个路径**只由章号拼成**。DB 层 `chapters` 是
-- `UNIQUE(book_id, chapter_number)` —— 允许 A 书第 1 章与 B 书第 1 章同时存在。
-- 于是两本书各自的 `seq` 都从 1 起，B 的 `v001.md` 覆盖 A 的 `v001.md`：
--
--     A 的版本列表仍列出 v001（DB 行还在）
--     但读出来是 B 的文本        （文件被覆盖）
--
-- 这是「版本历史看起来完整、内容却是别人的」，比直接报错难发现得多。
--
-- 修法与 chapters 正文一致：版本内容路径改为
-- `books/<bookId>/workspace/chapter-NNN/versions/vNNN.md`，
-- 因此需要把 book_id 记在版本行上 —— 读版本文件时才能拼出正确路径。
--
-- ## 为什么冗余存储（chapter_id 已能推出书）
--
-- 与同表的 `chapter_number` 同一理由：读版本文件是**热路径**
-- （列表 + 每次打开版本），若每次都要 `JOIN chapters` 才能拼路径，
-- 一是多一次查询，二是版本读取要依赖 chapters 行仍然存在。
-- 版本行自己带上路径所需的两项（书 + 章号），读取即可自足。
--
-- ## 为什么允许 NULL
--
-- 0018 之前落下的版本行没有这个信息。它们的 content_path 指向**旧布局**
-- （`workspace/chapter-NNN/...`），迁移时按老路径原样保留即可 ——
-- 强行推断书会让「读旧版本」指向一个可能不存在的路径。
-- 读取逻辑对 NULL 走旧路径，对新行走新路径。
--
-- ## 索引
--
-- ⚠ 不加新索引：现有 `idx_manuscript_versions_chapter(chapter_id, seq)`
--   已覆盖唯一的查询形态（按章列版本）。book_id 只参与路径拼接，不做过滤。
--   加索引只有写放大（同 0013/0014/0016 的判断）。
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE manuscript_versions ADD COLUMN book_id TEXT;
